const draft = JSON.parse(await fs.readFile(IN_FILE, "utf8"));
if (!Array.isArray(draft) || draft.length !== 100) {
  throw new Error(`Ожидались 100 пар в черновике, получено: ${draft.length}`);
}

const pairs = [];
const ids = new Set();
for (const item of draft) {
  if (EXCLUDED.has(item.id)) continue;
  if (!item.question || !item.answer) throw new Error(`Пустая пара: ${item.id}`);
  if (ids.has(item.id)) throw new Error(`Повторный id: ${item.id}`);
  ids.add(item.id);
  const fix = FIXES[item.id];
  pairs.push({ ...item, ...(fix ?? {}), status: "approved" });
}

