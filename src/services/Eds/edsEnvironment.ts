/**
 * Где открыта страница: обычный браузер или встроенный в приложение.
 *
 * Зачем отдельная проверка до диагностики плагина: у встроенного браузера
 * (Electron) нет расширения CAdES и быть не может — подпись там недоступна
 * принципиально. Человеку нужно сказать это сразу и коротко, а не гонять его
 * по списку «проверьте токен, расширение, перезапустите браузер», где ни один
 * пункт не относится к делу.
 */

export const isEmbeddedBrowser = (): boolean => {
  if (typeof navigator === "undefined") return false;

  return /Electron|OpenCode/i.test(navigator.userAgent);
};

