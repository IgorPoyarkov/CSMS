const hasRailwayMilitary = (text: string) =>
  /железнодорожн[а-яё]*\s+подвижн/.test(text);

const hasArmament = (text: string) =>
  /вооружен|военн[а-яё]*\s+и\s+специальн[а-яё]*\s+техник/.test(text);

const hasNuclearWeapons = (text: string) => /ядерн[а-яё]*\s+оружейн/.test(text);

const hasNuclear = (text: string) => /ядерн|радиоактивн|радиационн/.test(text);

