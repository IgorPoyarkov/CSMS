export type DelegationRoleId = "head" | "unit" | "worker" | "system";

export interface DelegationRole {
  id: DelegationRoleId;
  name: string;
  badge: string;
  text: string;
  points: string[];
}

export interface DelegationStep {
  title: string;
  text: string;
  meta: string;
}

export type HierarchyNodeModifier =
  | "customer"
  | "head"
  | "unit"
  | "worker"
  | "manager";

export interface HierarchyNode {
  name: string;
  caption: string;
  modifier: HierarchyNodeModifier;
}

export interface HierarchyLevel {
  nodes: HierarchyNode[];
  // Подпись на стрелке к следующему уровню (последний уровень её не использует)
  downLabel?: string;
  // Подпись на стрелке между узлами одного уровня
  acrossLabel?: string;
}

export interface HierarchyBranch {
  id: string;
  title: string;
  hint: string;
  levels: HierarchyLevel[];
}

